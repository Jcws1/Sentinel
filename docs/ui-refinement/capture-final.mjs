import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../../frontend/package.json', import.meta.url));
const { chromium } = require('@playwright/test');
const directory = new URL('./final/', import.meta.url);
await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5183');
await page.getByRole('heading', { name: 'Tactical Map', exact: true }).waitFor();
await page.screenshot({ path: fileURLToPath(new URL('default.png', directory)) });
await page.getByRole('button', { name: 'Open Command Picture', exact: true }).click();
await page.getByRole('button', { name: 'Vertical Profile options', exact: true }).click();
await page.getByRole('menuitem', { name: 'Open to Side', exact: true }).click();
await page.getByRole('heading', { name: 'Vertical Profile', exact: true }).waitFor();
await page.mouse.click(1000, 200);
await page.screenshot({ path: fileURLToPath(new URL('split.png', directory)) });
await page.getByRole('button', { name: 'Timeline options', exact: true }).click();
await page.getByRole('menuitem', { name: 'Open to Side', exact: true }).focus();
await page.screenshot({ path: fileURLToPath(new URL('menu-focus.png', directory)) });
await writeFile(new URL('capture.json', directory), JSON.stringify({ date: new Date().toISOString(), browser: browser.version(), viewport: page.viewportSize(), errors }, null, 2));
await browser.close();
