def post(client, body):
    return client.post("/api/simulation/v1/commands", content=json.dumps(body))


def run_all(path, dataset=DATASET):
    """Submit every mission's command sequence in order; return raw responses by command ID."""
    responses = {}
    with TestClient(create_app(str(path), False)) as client:
        for mission in dataset["missions"]:
            for body in mission["commands"]:
                response = post(client, body)
                assert response.status_code == 200, response.text
                responses[body["command"]["command_id"]] = response.content
    return responses


def results(raw):
    return json.loads(raw)["results_by_timestamp"]


def drone_rows(body):
    return {at: {row["drone_id"]: row for row in rows} for at, rows in body["samples_by_timestamp"].items()}


