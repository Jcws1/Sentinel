@pytest.mark.parametrize("mission", DATASET["missions"], ids=lambda m: m["key"])
def test_boundary_distance_polygon_and_band_cases_are_inclusive(recorded, mission):
    _, responses = recorded
    tag = mission["key"][0].upper()
    start = results(responses[f"S9-{tag}-START"])
    first_contact = sorted(start)[2]
    pairs = {(i["red_drone_id"], i["blue_drone_id"]): i for i in start[first_contact]["interactions"]}
    edge = pairs[(f"R-{tag}-EDGE", f"B-{tag}-EDGE")]  # slanted edge point, exactly 250 m apart
    assert edge["separation_m"] == 250.0
    assert (f"R-{tag}-FLOOR", f"B-{tag}-FLOOR") in pairs  # altitude band minimum
    assert (f"R-{tag}-CEIL", f"B-{tag}-CEIL") in pairs  # altitude band maximum
    assert (f"R-{tag}-APEX", f"B-{tag}-APEX") in pairs  # both on a polygon vertex, 200 m apart
    assert (f"R-{tag}-VERTEX", f"B-{tag}-VERTEX") not in pairs  # 250.001 m: just outside radius
    assert not any(red.endswith(INELIGIBLE_SUFFIXES) for red, _ in pairs)


def shuffled(body, seed, rules_seed=99):
    """Permute every snapshot's drone array; permute rules with one per-run seed.

    The profile body is part of immutable calibration identity (C07/C15), so a
    run keeps one rules order; a different order under the same identity is a
    409 conflict, covered separately below.
    """
    rng = random.Random(seed)
    body = copy.deepcopy(body)
    for rows in body["samples_by_timestamp"].values():
        rng.shuffle(rows)
    random.Random(rules_seed).shuffle(body["calibration_profile"]["rules"])
    return body


def test_input_array_order_does_not_affect_results(recorded, tmp_path):
    _, responses = recorded
    permuted = copy.deepcopy(DATASET)
    for mission in permuted["missions"]:
        mission["commands"] = [shuffled(body, i) for i, body in enumerate(mission["commands"])]
    again = run_all(tmp_path / "permuted.sqlite3", permuted)
    for command_id, raw in responses.items():
        assert json.loads(again[command_id]) == json.loads(raw)


def test_reordered_rules_under_one_profile_identity_are_a_calibration_conflict(tmp_path):
    start, hold = DATASET["missions"][0]["commands"][:2]
    with TestClient(create_app(str(tmp_path / "rules.sqlite3"), False)) as client:
        assert post(client, start).status_code == 200
        reordered = copy.deepcopy(hold)
        reordered["calibration_profile"]["rules"].reverse()
        response = post(client, reordered)
        assert (response.status_code, response.json()["command_ack"]["error_code"]) == (409, "CALIBRATION_ID_CONFLICT")
        assert client.get("/api/simulation/v1/runs").json()[0]["state"] == "RUNNING"


def test_simultaneous_effects_do_not_depend_on_pair_processing_order(monkeypatch):
    ordinary = resolver.candidate_steps
    reversed_timestamps = 0

    def reversed_pairs(request, drones):
        items = list(ordinary(request, drones))
        pairs = [item for item in items if item is not None]
        yield from reversed(pairs)
    for mission in DATASET["missions"]:
        for body in mission["commands"]:
            expected = resolver.resolve_drone_attack_simulation(copy.deepcopy(body))
            monkeypatch.setattr(resolver, "candidate_steps", reversed_pairs)
            reordered = resolver.resolve_drone_attack_simulation(copy.deepcopy(body))
            monkeypatch.setattr(resolver, "candidate_steps", ordinary)
            for at, value in expected["results_by_timestamp"].items():
                other = reordered["results_by_timestamp"][at]
                assert other["drone_health"] == value["drone_health"]
                key = lambda i: (i["red_drone_id"], i["blue_drone_id"])  # noqa: E731
                assert sorted(other["interactions"], key=key) == sorted(value["interactions"], key=key)
                # The reversal really took effect: pairs were processed in the opposite order.
                assert [key(i) for i in other["interactions"]] == [key(i) for i in reversed(value["interactions"])]
                reversed_timestamps += len(value["interactions"]) > 1
                # Every health change is exactly the clamped sum of that drone's applied deltas.
                deltas = Counter()
                for interaction in value["interactions"]:
                    for effect in interaction["effects"]:
                        deltas[effect["subject_drone_id"]] += effect["health_delta"]
                for row in value["drone_health"]:
                    assert row["health_after"] == max(0, min(100, row["health_before"] + deltas[row["drone_id"]]))
    assert reversed_timestamps > 0


