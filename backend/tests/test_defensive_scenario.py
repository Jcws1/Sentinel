@pytest.mark.parametrize("mission", DATASET["missions"], ids=lambda m: m["key"])
def test_hold_resume_abort_idempotency_and_conflicts_follow_section_8(tmp_path, mission):
    start, hold, resume, abort = mission["commands"]
    with TestClient(create_app(str(tmp_path / "lifecycle.sqlite3"), False)) as client:
        assert post(client, start).json()["command_ack"]["run_status"] == "RUNNING"
        early = copy.deepcopy(resume)
        early["command"]["command_id"] += "-EARLY"
        assert post(client, early).json()["command_ack"]["error_code"] == "RUN_NOT_HELD"
        held = post(client, hold).json()
        assert held["command_ack"]["run_status"] == "HELD"
        assert held["results_by_timestamp"] == {} and hold["samples_by_timestamp"]  # samples supplied, no outcomes
        resumed = post(client, resume).json()
        assert resumed["command_ack"]["run_status"] == "RUNNING"
        first = sorted(resumed["results_by_timestamp"])[0]
        corrected = {row["drone_id"] for row in resumed["results_by_timestamp"][first]["drone_health"] if row["state_discontinuity"]}
        assert corrected == {mission["repairedOnResume"]}  # supplied health is authoritative and visible
        later = [row for at in sorted(resumed["results_by_timestamp"])[1:] for row in resumed["results_by_timestamp"][at]["drone_health"]]
        assert not any(row["state_discontinuity"] for row in later)
        assert post(client, abort).json()["command_ack"]["run_status"] == "ABORTED"
        for action, code in (("START", "RUN_TERMINAL"), ("HOLD", "RUN_TERMINAL"), ("RESUME", "RUN_NOT_HELD"), ("ABORT", "RUN_TERMINAL")):
            late = copy.deepcopy({"START": start, "HOLD": hold, "RESUME": resume, "ABORT": abort}[action])
            late["command"]["command_id"] += "-AFTER-ABORT"
            response = post(client, late)
            assert (response.status_code, response.json()["command_ack"]["error_code"]) == (409, code)
        original = post(client, start)
        assert post(client, start).content == original.content  # completed identical retry after ABORT
        altered = copy.deepcopy(start)
        altered["resolution"]["interaction_radius_m"] = 249
        assert post(client, altered).json()["command_ack"]["error_code"] == "COMMAND_ID_CONFLICT"
        run = client.get(f"/api/simulation/v1/runs/{mission_identity(mission['missionId'])}").json()
        assert (run["state"], run["phase"]) == ("ABORTED", "ready")


def frames_by_effective_time(repository, mid):
    recording = repository.recording_for(mid).id
    frames = {}
    for effective_at, stored in repository.db.execute(
            "SELECT effective_at, frame_json FROM frames WHERE recording_id=? ORDER BY sequence", (recording,)):
        frames[effective_at] = json.loads(decode_text(stored))
    return frames


def test_recorded_inspection_retains_ids_draws_transitions_and_order_after_restart(recorded):
    path, responses = recorded
    with TestClient(create_app(str(path), False)) as client:  # a new app instance reopens the database
        for mission in DATASET["missions"]:
            mid = mission_identity(mission["missionId"])
            commands = client.get(f"/api/simulation/v1/runs/{mid}/commands").json()
            assert [c["action"] for c in commands] == ["START", "HOLD", "RESUME", "ABORT"]
            assert {c["state"] for c in commands} == {"completed"}
            for body in mission["commands"]:
                command_id = body["command"]["command_id"]
                stored = client.get("/api/simulation/v1/command-result", params={"command_id": command_id})
                assert stored.content == responses[command_id]
            events, after = [], -1
            while True:
                page = client.get(f"/api/missions/{mid}/events", params={"after": after, "limit": 500}).json()
                events += page["events"]
                if page.get("nextAfter") is None:
                    break
                after = page["nextAfter"]
            recorded_interactions = [(e["effectiveAt"], e["extensions"][NAMESPACE]["result"])
                                     for e in events if e["type"] == "simulation.v1.interaction"]
            expected = [(at, interaction) for body in mission["commands"]
                        for at, value in sorted(results(responses[body["command"]["command_id"]]).items())
                        for interaction in value["interactions"]]
            assert recorded_interactions == expected  # IDs, draws, effects and ordering
            assert [e["sequence"] for e in events] == sorted(e["sequence"] for e in events)
            assert events[-1]["type"] == "simulation.v1.command-completed"
            frames = frames_by_effective_time(client.app.state.service.repository, mid)
            for body in mission["commands"]:
                for at, value in results(responses[body["command"]["command_id"]]).items():
                    entities = {e["label"]: e for e in frames[at]["entities"].values()}
                    for row in value["drone_health"]:
                        detail = entities[row["drone_id"]]["extensions"][NAMESPACE]
                        assert (detail["health"], detail["reportedStatus"]) == (row["health_after"], row["status_after"])
            world = client.get(f"/api/missions/{mid}/world").json()
            assert world["mission"]["lifecycle"] == "completed"


def test_larger_backend_variant_keeps_the_resolver_criteria():
    dataset = defensive_scenario.build(25)  # phase timing is tuned for the UI scale; criteria below are scale-free
    for mission in dataset["missions"]:
        for body in mission["commands"]:
            first = resolver.resolve_drone_attack_simulation(copy.deepcopy(body))
            assert resolver.resolve_drone_attack_simulation(shuffled(body, 7)) == first
            for value in first["results_by_timestamp"].values():
                pairs = [(i["red_drone_id"], i["blue_drone_id"]) for i in value["interactions"]]
                assert len(pairs) == len(set(pairs))
                for row in value["drone_health"]:
                    if row["drone_id"].startswith(NEUTRAL_PREFIXES) or row["drone_id"].endswith(INELIGIBLE_SUFFIXES):
                        assert row["health_after"] == row["health_before"]
        assert sum(len(rows) for rows in mission["commands"][0]["samples_by_timestamp"].values()) > 2000
