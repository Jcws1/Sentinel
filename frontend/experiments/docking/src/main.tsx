import './session';
import './style.css';
const engine = new URLSearchParams(location.search).get('engine') === 'golden' ? 'golden':'flex';
const root=document.getElementById('root')!;
root.innerHTML='<header><b>Phase 0 docking probe</b> <a href="/?engine=flex">FlexLayout</a> <a href="/?engine=golden">Golden Layout</a> <button id="split">Split chart</button> <button id="pop">Pop chart</button> <button id="open">Open chart</button><button id="close">Close chart</button><output id="error"></output></header><main id="layout"></main>';
const host=document.getElementById('layout')!;
const api=engine === 'flex' ? (await import('./flex')).startFlex(host) : (await import('./golden')).startGolden(host);
document.getElementById('split')!.onclick=api.split;
document.getElementById('pop')!.onclick=()=>{try{api.popout();}catch(error){document.getElementById('error')!.textContent=String(error);}};
document.getElementById('open')!.onclick=api.open;
document.getElementById('close')!.onclick=api.close;
window.probe={engine,layout:api.layout};
